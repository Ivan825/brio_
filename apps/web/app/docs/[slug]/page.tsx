import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { DOCS, docPage, renderDoc } from "@/lib/docs";

export const dynamicParams = false;

export function generateStaticParams() {
  return DOCS.map((d) => ({ slug: d.slug }));
}

export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }): Promise<Metadata> {
  const page = docPage((await params).slug);
  return page ? { title: page.title, description: page.summary } : {};
}

export default async function DocPage({ params }: { params: Promise<{ slug: string }> }) {
  const page = docPage((await params).slug);
  if (!page) notFound();
  const { html, headings } = renderDoc(page);
  return (
    <div className="flex gap-8">
      {/* The repository's own Markdown, rendered at build time with raw HTML escaped (lib/docs.ts). */}
      {/* biome-ignore lint/security/noDangerouslySetInnerHtml: generated by marked from reviewed docs, raw HTML escaped */}
      <article className="doc min-w-0 flex-1" data-testid="doc" dangerouslySetInnerHTML={{ __html: html }} />
      {headings.length > 2 && (
        <nav aria-label="On this page" className="sticky top-20 hidden h-fit w-48 shrink-0 xl:block">
          <p className="mb-1.5 font-mono text-2xs uppercase tracking-[0.08em] text-fg-subtle">On this page</p>
          <ul className="flex flex-col gap-1 text-xs">
            {headings.map((h) => (
              <li key={h.id}>
                <a href={`#${h.id}`} className="text-fg-muted hover:text-fg">
                  {h.text}
                </a>
              </li>
            ))}
          </ul>
        </nav>
      )}
    </div>
  );
}
